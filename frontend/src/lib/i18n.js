// Traduce una clave del diccionario del idioma `lang` con interpolación
// de placeholders tipo {name}, {n}, {total}, {stars}, {status}, etc.
export function t(lang, key, replacements) {
  const dict = I18N[lang] || I18N.es;
  let str = dict[key] !== undefined ? dict[key] : key;
  if (replacements) {
    Object.keys(replacements).forEach(k => {
      str = str.split('{' + k + '}').join(replacements[k]);
    });
  }
  return str;
}

// Devuelve la versión correcta según el idioma de un texto que puede
// guardarse como objeto con claves {es, en} (contenido demo bilingüe)
// o como string único (contenido escrito por el usuario).
export function l10nValue(lang, value) {
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    return value[lang] || value.es || '';
  }
  return value || '';
}